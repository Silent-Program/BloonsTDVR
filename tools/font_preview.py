def render(text, scale=4, pad=4):
    width = (len(text) * 6 - 1) * scale + pad * 2
    height = 7 * scale + pad * 2
    img = Image.new('RGB', (width, height), (18, 18, 22))
    px = img.load()
    for index, char in enumerate(text.upper()):
        glyph = FONT.get(char)
        if glyph is None:
            continue
        for col, bits in enumerate(glyph):
            for row in range(7):
                if not bits & (1 << row):
                    continue
                x0 = pad + (index * 6 + col) * scale
                y0 = pad + row * scale
                for dx in range(scale):
                    for dy in range(scale):
                        px[x0 + dx, y0 + dy] = (255, 255, 255)
    return img


if __name__ == '__main__':
    lines = ["CURSOR LOCKED", "CURSOR FREE", "PRESS TAB TO UNLOCK", "F TO PLACE TOWER"]
    strip = Image.new('RGB', (max(render(t).width for t in lines), sum(render(t).height + 8 for t in lines)), (18, 18, 22))
    y = 0
    for line in lines:
        img = render(line)
        strip.paste(img, (0, y))
        y += img.height + 8
    strip.save('font_preview.png')
    print('wrote font_preview.png', strip.size)